using Microsoft.AspNetCore.DataProtection.EntityFrameworkCore;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;

namespace AspireBoot.Core.Persistence.Auditing;

/// <summary>
/// Explicit lists deciding what the audit trail records. Classification is by CLR type and property name,
/// so a new owned or complex type must be added here (an architecture test enforces it).
/// </summary>
public static class AuditPolicy
{
    public const string MaskedValue = "***";

    /// <summary>
    /// Entity types never audited. The claim tables are unused (RBAC uses roles) and have store-generated integer keys,
    /// which the audit cannot record before save; if claims are ever adopted, give them client-generated keys and audit them.
    /// </summary>
    public static readonly IReadOnlySet<Type> ExcludedTypes = new HashSet<Type>
    {
        typeof(AuditEntry),
        typeof(DataProtectionKey),
        typeof(IdentityUserClaim<Guid>),
        typeof(IdentityRoleClaim<Guid>),
    };

    /// <summary>
    /// Owned and complex types: <c>true</c> = excluded (only <c>{"data":{"changed":true}}</c> is recorded, never values),
    /// <c>false</c> = included in the owner row.
    /// </summary>
    public static readonly IReadOnlyDictionary<Type, bool> OwnedTypes = new Dictionary<Type, bool>
    {
        [typeof(IdentityPasskeyData)] = true,
    };

    /// <summary>Property names masked on every entity type.</summary>
    public static readonly IReadOnlyList<string> MaskedPropertyNames =
    [
        "SecurityStamp",
        "ConcurrencyStamp",
        "PasswordHash",
        "xmin",
        "NormalizedEmail",
        "NormalizedUserName",
    ];

    /// <summary>Property names masked only on one (open generic) CLR type.</summary>
    public static readonly IReadOnlyList<(Type EntityType, string Property)> MaskedTypeProperties =
    [
        (typeof(IdentityUserToken<>), nameof(IdentityUserToken<int>.Value)),
        (typeof(IdentityUserLogin<>), nameof(IdentityUserLogin<int>.ProviderKey)),
    ];

    public static bool IsMasked(Type entityClrType, string propertyName)
    {
        ArgumentNullException.ThrowIfNull(entityClrType);

        if (MaskedPropertyNames.Contains(propertyName, StringComparer.Ordinal))
        {
            return true;
        }

        var definition = entityClrType.IsGenericType ? entityClrType.GetGenericTypeDefinition() : entityClrType;
        foreach (var (type, property) in MaskedTypeProperties)
        {
            if (type == definition && string.Equals(property, propertyName, StringComparison.Ordinal))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>True when the entity type is a root type that produces audit rows.</summary>
    public static bool IsAudited(IEntityType entityType)
    {
        ArgumentNullException.ThrowIfNull(entityType);
        return !entityType.IsOwned() && !ExcludedTypes.Contains(entityType.ClrType) && entityType.FindPrimaryKey() is not null;
    }

    public static bool IsExcludedOwned(IEntityType ownedType)
    {
        ArgumentNullException.ThrowIfNull(ownedType);
        return !OwnedTypes.TryGetValue(ownedType.ClrType, out var excluded) || excluded;
    }

    /// <summary>
    /// True when the key value is generated by the store (identity, default SQL, sequence) and so unknown before save.
    /// Guid keys with a client-side generator and keys without generation are accepted.
    /// </summary>
    public static bool HasStoreGeneratedKey(IEntityType entityType)
    {
        ArgumentNullException.ThrowIfNull(entityType);
        var key = entityType.FindPrimaryKey();
        if (key is null)
        {
            return false;
        }

        foreach (var property in key.Properties)
        {
            if (property.GetDefaultValueSql() is not null || property.GetComputedColumnSql() is not null)
            {
                return true;
            }

            if (property.ValueGenerated != ValueGenerated.Never
                && property.ClrType != typeof(Guid)
                && property.GetValueGeneratorFactory() is null)
            {
                return true;
            }
        }

        return false;
    }
}